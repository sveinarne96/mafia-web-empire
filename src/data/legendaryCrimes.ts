// Get 5 random crimes that change daily
export function getDailyLegendaryCrimes(): LegendaryCrime[] {
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const shuffled = [...LEGENDARY_CRIME_POOL].sort((a, b) => {
    const hashA = (a.id.split('').reduce((h, c) => ((h << 5) - h + c.charCodeAt(0)) | 0, seed) >>> 0);
    const hashB = (b.id.split('').reduce((h, c) => ((h << 5) - h + c.charCodeAt(0)) | 0, seed) >>> 0);
    return hashA - hashB;
  });
  return shuffled.slice(0, 5);
}

// Time until next reset (midnight UTC)
export function getTimeUntilReset(): number {
  const now = new Date();
  const tomorrow = new Date(now);
  tomorrow.setUTCDate(tomorrow.getUTCDate() + 1);
  tomorrow.setUTCHours(0, 0, 0, 0);
  return tomorrow.getTime() - now.getTime();
}

